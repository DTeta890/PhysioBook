function makeDateTime(dayOffset: number, hour: number, minute: number): string {
  const monday = startOfWeek(new Date(), { weekStartsOn: 1 })
  const day = addDays(monday, dayOffset)
  return `${format(day, 'yyyy-MM-dd')}T${hour.toString().padStart(2, '0')}:${minute.toString().padStart(2, '0')}:00`
}

